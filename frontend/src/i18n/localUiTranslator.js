const EN_TO_ID = Object.fromEntries(
    Object.entries(ID_TO_EN).map(([id, en]) => [en, id]),
);

const ATTRIBUTES = ["placeholder", "title", "aria-label", "alt"];
const SKIP_TAGS = new Set(["SCRIPT", "STYLE", "NOSCRIPT", "TEXTAREA", "CODE", "PRE"]);

function isBrowser() {
    return typeof window !== "undefined" && typeof document !== "undefined";
}

export function getAppLanguage() {
    if (!isBrowser()) return DEFAULT_LANGUAGE;

    const stored = localStorage.getItem(APP_LANGUAGE_KEY);
    return SUPPORTED_LANGUAGES.includes(stored) ? stored : DEFAULT_LANGUAGE;
}

export function setAppLanguage(language) {
    const safeLanguage = SUPPORTED_LANGUAGES.includes(language) ? language : DEFAULT_LANGUAGE;

    if (!isBrowser()) return safeLanguage;

    localStorage.setItem(APP_LANGUAGE_KEY, safeLanguage);

    window.dispatchEvent(
        new CustomEvent("app-language-change", {
            detail: { language: safeLanguage },
        }),
    );

    // Alias event untuk komponen lama/baru yang memakai nama event berbeda.
    window.dispatchEvent(
        new CustomEvent("ypa-ui-language-change", {
            detail: { language: safeLanguage },
        }),
    );

    return safeLanguage;
}

// Alias supaya LanguageSwitcher lama tetap aman.
export const getUiLanguage = getAppLanguage;
export const saveUiLanguage = setAppLanguage;

export function translateText(value, language = getAppLanguage()) {
    const raw = String(value ?? "");
    const trimmed = raw.trim();

    if (!trimmed) return raw;

    const dictionary = language === "en" ? ID_TO_EN : EN_TO_ID;
    const translated = dictionary[trimmed];

    if (!translated) return raw;

    const prefix = raw.match(/^\s*/)?.[0] || "";
    const suffix = raw.match(/\s*$/)?.[0] || "";

    return `${prefix}${translated}${suffix}`;
}

export const translateUiText = translateText;

function shouldSkipElement(element) {
    if (!element) return true;
    if (SKIP_TAGS.has(element.tagName)) return true;
    if (element.closest?.("[data-no-auto-translate='true']")) return true;
    return false;
}

function translateTextNode(node, language) {
    const parent = node.parentElement;
    if (shouldSkipElement(parent)) return;

    const next = translateText(node.nodeValue, language);
    if (next !== node.nodeValue) node.nodeValue = next;
}

function translateElementAttributes(element, language) {
    if (shouldSkipElement(element)) return;

    ATTRIBUTES.forEach((attribute) => {
        if (!element.hasAttribute?.(attribute)) return;

        const current = element.getAttribute(attribute);
        const next = translateText(current, language);

        if (next !== current) element.setAttribute(attribute, next);
    });
}

export function translateRoot(root = isBrowser() ? document.body : null, language = getAppLanguage()) {
    if (!root || !isBrowser()) return;

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const textNodes = [];

    while (walker.nextNode()) {
        textNodes.push(walker.currentNode);
    }

    textNodes.forEach((node) => translateTextNode(node, language));

    if (root.nodeType === Node.ELEMENT_NODE) {
        translateElementAttributes(root, language);
    }

    root.querySelectorAll?.("*").forEach((element) => translateElementAttributes(element, language));
}

export const translateUiTree = translateRoot;

export function useAppLanguage() {
    const [language, setLanguageState] = useState(getAppLanguage);

    const setLanguage = useCallback((nextLanguage) => {
        const safeLanguage = setAppLanguage(nextLanguage);
        setLanguageState(safeLanguage);
        return safeLanguage;
    }, []);

    useEffect(() => {
        if (!isBrowser()) return undefined;

        const handleChange = (event) => {
            setLanguageState(event?.detail?.language || getAppLanguage());
        };

        const handleStorage = (event) => {
            if (event.key && event.key !== APP_LANGUAGE_KEY) return;
            setLanguageState(getAppLanguage());
        };

        window.addEventListener("app-language-change", handleChange);
        window.addEventListener("ypa-ui-language-change", handleChange);
        window.addEventListener("storage", handleStorage);

        return () => {
            window.removeEventListener("app-language-change", handleChange);
            window.removeEventListener("ypa-ui-language-change", handleChange);
            window.removeEventListener("storage", handleStorage);
        };
    }, []);

    return [language, setLanguage];
}

